// Standalone enrichment process: GitHub -> Neon `trust_edges`. No SQLite.
//
// Deliberately imports only DB-free modules (githubCore, vouchParser) plus `pg`,
// so this process is independent of the app's local store. It is the only writer;
// the app reads with a SELECT-only role.
//
// Usage:
//   npm run crawl:shared -- --init                 create table + indexes, then exit
//   npm run crawl:shared -- --limit 100 --commits 20
//   npm run crawl:shared -- --dry-run
import "dotenv/config";
import { Pool } from "pg";
import { entryKeys, parseVouchFile } from "../src/server/vouchParser";
import { fileCommits, getFile, octokit, sleep, withRetry } from "../src/server/githubCore";

const arg = (name: string, def: number) => {
  const i = process.argv.indexOf(name);
  return i > 0 ? Number(process.argv[i + 1]) : def;
};
const has = (name: string) => process.argv.includes(name);

const LIMIT = arg("--limit", 100);
const MAX_COMMITS = arg("--commits", 20); // 0 = skip history, voucher stays NULL
const DRY_RUN = has("--dry-run");

const url = process.env.NEON_WRITE_URL;
if (!url && !DRY_RUN) {
  console.error("NEON_WRITE_URL is not set. Use the DIRECT (non-pooler) owner connection string.");
  process.exit(1);
}
if (url?.includes("-pooler")) {
  console.warn("warning: NEON_WRITE_URL looks pooled; a direct (non-pooler) string is preferred for a writer.");
}
const pool = url ? new Pool({ connectionString: url, max: 4 }) : undefined;

const DDL = `
CREATE TABLE IF NOT EXISTS trust_edges (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project     text NOT NULL,
  login       text NOT NULL,
  platform    text NOT NULL DEFAULT 'github',
  status      text NOT NULL CHECK (status IN ('vouched','denounced')),
  note        text,
  voucher     text,
  occurred_at timestamptz,
  commit_sha  text,
  source      text NOT NULL DEFAULT 'crawl',
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (project, login, platform)
);
CREATE INDEX IF NOT EXISTS trust_edges_login   ON trust_edges (lower(login));
CREATE INDEX IF NOT EXISTS trust_edges_project ON trust_edges (lower(project));
`;

type Edge = {
  login: string;
  platform: string;
  status: "vouched" | "denounced";
  note: string | null;
  voucher: string | null;
  occurred_at: string | null;
  commit_sha: string | null;
};

/** Find public VOUCHED.td files, preferring canonical paths when a repo has several. */
async function search(): Promise<[string, string][]> {
  const hits = new Map<string, string>();
  for (let page = 1; hits.size < LIMIT && page <= 10; page++) {
    const { data } = await withRetry(() => octokit().search.code({ q: "filename:VOUCHED.td", per_page: 100, page }));
    for (const item of data.items) {
      const name = item.repository.full_name;
      const prev = hits.get(name);
      if (!prev || item.path === "VOUCHED.td" || (item.path === ".github/VOUCHED.td" && prev !== "VOUCHED.td"))
        hits.set(name, item.path);
    }
    console.log(`search page ${page}: ${data.items.length} hits (total ${data.total_count})`);
    if (data.items.length < 100) break;
    await sleep(7000); // code search: 10 req/min
  }
  return [...hits].slice(0, LIMIT);
}

/** raw.githubusercontent.com does not count against the REST rate limit. */
async function rawAt(fullName: string, sha: string, path: string): Promise<string | null> {
  const res = await fetch(`https://raw.githubusercontent.com/${fullName}/${sha}/${path}`);
  if (res.status === 404) return null;
  if (!res.ok) throw new Error(`raw ${res.status}`);
  return res.text();
}

/**
 * Who added each entry, from the file's git history. The voucher is the commit
 * author only when GitHub resolves it to an account — never guessed.
 */
async function attribute(fullName: string, path: string) {
  const found = new Map<string, { voucher: string | null; occurred_at: string; commit_sha: string }>();
  if (MAX_COMMITS <= 0) return found;
  const commits = await fileCommits(fullName, path, MAX_COMMITS);
  let prev = new Map<string, ReturnType<typeof entryKeys> extends Map<string, infer V> ? V : never>();
  for (const c of commits) {
    const text = await rawAt(fullName, c.sha, path);
    const cur = entryKeys(text ?? "");
    for (const [key, e] of cur) {
      const before = prev.get(key);
      if (!before || before.status !== e.status) {
        found.set(key, { voucher: c.author ?? null, occurred_at: c.date, commit_sha: c.sha });
      }
    }
    prev = cur;
  }
  return found;
}

async function indexOne(fullName: string, path: string) {
  const file = await getFile(fullName, path);
  if (!file) return { skipped: true, edges: 0 };
  const entries = parseVouchFile(file.text);
  if (entries.length === 0) return { skipped: true, edges: 0 };

  let attrib = new Map<string, { voucher: string | null; occurred_at: string; commit_sha: string }>();
  try {
    attrib = await attribute(fullName, path);
  } catch (err) {
    console.warn(`  ${fullName}: history unavailable (${(err as Error).message}); vouchers stay unknown`);
  }

  const edges: Edge[] = entries.map((e) => {
    const a = attrib.get(`${e.platform}:${e.login.toLowerCase()}`);
    return {
      login: e.login,
      platform: e.platform,
      status: e.status,
      note: e.note,
      voucher: a?.voucher ?? null,
      occurred_at: a?.occurred_at ?? null,
      commit_sha: a?.commit_sha ?? file.sha,
    };
  });

  if (DRY_RUN || !pool) {
    console.log(`  [dry-run] ${fullName}: ${edges.length} edges`);
    return { skipped: false, edges: edges.length };
  }
  await upsertProject(fullName, edges);
  return { skipped: false, edges: edges.length };
}

/** One transaction per project: upsert current entries, drop ones no longer listed. */
async function upsertProject(project: string, edges: Edge[]) {
  const client = await pool!.connect();
  try {
    await client.query("BEGIN");
    // Single multi-row statement: one round trip instead of one per edge.
    const cols = 8;
    const values = edges.flatMap((e) => [project, e.login, e.platform, e.status, e.note, e.voucher, e.occurred_at, e.commit_sha]);
    const tuples = edges
      .map((_, i) => `(${Array.from({ length: cols }, (_, c) => `$${i * cols + c + 1}`).join(",")})`)
      .join(",");
    await client.query(
      `INSERT INTO trust_edges (project, login, platform, status, note, voucher, occurred_at, commit_sha)
       VALUES ${tuples}
       ON CONFLICT (project, login, platform) DO UPDATE SET
         status      = EXCLUDED.status,
         note        = EXCLUDED.note,
         voucher     = COALESCE(EXCLUDED.voucher, trust_edges.voucher),
         occurred_at = COALESCE(EXCLUDED.occurred_at, trust_edges.occurred_at),
         commit_sha  = COALESCE(EXCLUDED.commit_sha, trust_edges.commit_sha),
         source      = 'crawl',
         updated_at  = now()`,
      values,
    );
    // Reconcile removals so the shared index stays a true snapshot of the file.
    await client.query(
      `DELETE FROM trust_edges t
        WHERE t.project = $1
          AND NOT EXISTS (
            SELECT 1 FROM unnest($2::text[], $3::text[]) AS k(login, platform)
             WHERE k.login = t.login AND k.platform = t.platform
          )`,
      [project, edges.map((e) => e.login), edges.map((e) => e.platform)],
    );
    await client.query("COMMIT");
  } catch (err) {
    await client.query("ROLLBACK");
    throw err;
  } finally {
    client.release();
  }
}

async function main() {
  if (has("--init")) {
    if (!pool) throw new Error("NEON_WRITE_URL required for --init");
    await pool.query(DDL);
    console.log("trust_edges and indexes are in place.");
    await pool.end();
    return;
  }
  const hits = await search();
  console.log(`indexing ${hits.length} repositories${DRY_RUN ? " (dry run)" : ""}…`);
  const totals = { projects: 0, skipped: 0, failed: 0, edges: 0 };
  let i = 0;
  const worker = async () => {
    while (i < hits.length) {
      const [name, path] = hits[i++];
      try {
        const r = await indexOne(name, path);
        totals.projects++;
        if (r.skipped) totals.skipped++;
        totals.edges += r.edges;
      } catch (err) {
        totals.failed++;
        console.warn(`  ${name}: ${(err as Error).message}`);
      }
      if (totals.projects % 25 === 0) process.stdout.write(`  ${totals.projects}/${hits.length}\n`);
    }
  };
  await Promise.all(Array.from({ length: 4 }, worker));
  console.log(
    `\nSummary: ${totals.projects} projects (${totals.skipped} empty/missing, ${totals.failed} failed), ${totals.edges} edges written`,
  );
  await pool?.end();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
